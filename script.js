let currentLang = localStorage.getItem("arugabai-lang") || "en";
let messageId = 0;
const chatInstances = [];
let scriptedChatTimers = [];

function t(path) {
  return (
    path
      .split(".")
      .reduce((acc, key) => acc && acc[key], translations[currentLang]) || ""
  );
}

function applyTranslations() {
  document.documentElement.lang = currentLang === "fil" ? "fil" : "en";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = t(node.dataset.i18n);
    if (value) node.textContent = value;
  });
  document.querySelectorAll("[data-lang-pill]").forEach((node) => {
    node.classList.toggle("active", node.dataset.langPill === currentLang);
  });
  document.querySelectorAll(".interactive-chat").forEach((chat) => {
    resetInteractiveChat(chat);
  });
  initScriptedChat();
}

function hydrateIcons() {
  document.querySelectorAll("[data-icon]").forEach((node) => {
    node.innerHTML = icons[node.dataset.icon] || "";
  });
}

function chatShell() {
  return `
    <div class="chat-header">
      <img src="assets/arugabai-logo.png" alt="ArugaBai" class="logo">
      <div class="online"><span class="pulse-dot"></span><span data-chat-online>${t("bai.online")}</span></div>
    </div>
    <div class="chat-messages"></div>
  `;
}

function messageHtml(from, text) {
  const el = document.createElement("div");
  el.className = `message ${from}`;
  el.textContent = text;
  return el;
}

function typingEl() {
  const el = document.createElement("div");
  el.className = "typing";
  el.innerHTML = "<span></span><span></span><span></span>";
  return el;
}

function scrollMessages(box) {
  box.scrollTop = box.scrollHeight;
}

function resetInteractiveChat(chat) {
  const existing = chatInstances.find((entry) => entry.el === chat);
  if (existing) existing.timers.forEach(clearTimeout);

  chat.innerHTML = `${chatShell()}
    <div class="suggestions"></div>
    <div class="chat-input-wrap">
      <div class="chat-input">
        <input type="text" data-chat-input placeholder="${t("bai.inputPlaceholder")}">
        <button class="send-btn" type="button" aria-label="Send">${icons.send}</button>
      </div>
      <p class="chat-disclaimer">${t("bai.disclaimer")}</p>
    </div>`;

  const box = chat.querySelector(".chat-messages");
  const suggestions = chat.querySelector(".suggestions");
  const input = chat.querySelector("[data-chat-input]");
  const send = chat.querySelector(".send-btn");
  const state = { el: chat, timers: [], exchanges: 0 };
  const index = chatInstances.findIndex((entry) => entry.el === chat);
  if (index >= 0) chatInstances[index] = state;
  else chatInstances.push(state);

  box.appendChild(messageHtml("bai", t("bai.greeting")));
  [
    t("bai.suggested1"),
    t("bai.suggested2"),
    t("bai.suggested3"),
    t("bai.suggested4"),
  ].forEach((text) => {
    const button = document.createElement("button");
    button.type = "button";
    button.textContent = text;
    button.addEventListener("click", () => sendInteractive(chat, text));
    suggestions.appendChild(button);
  });

  send.addEventListener("click", () => sendInteractive(chat, input.value));
  input.addEventListener("keydown", (event) => {
    if (event.key === "Enter") sendInteractive(chat, input.value);
  });
}

function getChatState(chat) {
  return chatInstances.find((entry) => entry.el === chat);
}

function findResponse(text) {
  const lower = text.toLowerCase();
  const match = responseEntries.find((entry) =>
    entry.keywords.some((keyword) => lower.includes(keyword)),
  );
  return match ? match[currentLang] : t("bai.fallback");
}

function sendInteractive(chat, text) {
  const value = String(text || "").trim();
  const input = chat.querySelector("[data-chat-input]");
  const send = chat.querySelector(".send-btn");
  const box = chat.querySelector(".chat-messages");
  const suggestions = chat.querySelector(".suggestions");
  const state = getChatState(chat);
  if (!value || !state || input.disabled) return;

  suggestions.innerHTML = "";
  input.value = "";
  input.disabled = true;
  send.disabled = true;
  box.appendChild(messageHtml("user", value));
  const typing = typingEl();
  box.appendChild(typing);
  scrollMessages(box);

  const timer = setTimeout(
    () => {
      typing.remove();
      box.appendChild(messageHtml("bai", findResponse(value)));
      state.exchanges += 1;
      if (state.exchanges >= 2 && !chat.querySelector(".chat-nudge")) {
        const nudge = document.createElement("a");
        nudge.href = "signup";
        nudge.className = "chat-nudge";
        nudge.textContent = t("bai.ctaNudge");
        nudge.style.cssText =
          "align-self:center;color:#6FD1C2;font-size:12px;font-weight:800;text-decoration:underline;";
        box.appendChild(nudge);
      }
      input.disabled = false;
      send.disabled = false;
      input.focus();
      scrollMessages(box);
    },
    900 + Math.random() * 700,
  );
  state.timers.push(timer);
}

function initScriptedChat() {
  const chat = document.querySelector(".scripted-chat");
  if (!chat) return;

  function run() {
    scriptedChatTimers.forEach(clearTimeout);
    scriptedChatTimers = [];
    chat.innerHTML = chatShell();
    const box = chat.querySelector(".chat-messages");
    const add = (delay, maker) =>
      scriptedChatTimers.push(
        setTimeout(() => {
          maker(box);
          scrollMessages(box);
        }, delay),
      );

    add(900, (target) =>
      target.appendChild(
        messageHtml(
          "bai",
          t("bai.scriptedGreeting"),
        ),
      ),
    );
    add(2600, (target) => {
      const card = document.createElement("div");
      card.className = "summary-card";
      const title = document.createElement("strong");
      title.textContent = t("bai.scriptedSummaryTitle");
      card.appendChild(title);
      [
        [t("bai.scriptedAvgBp"), "142 / 88", "alert"],
        [t("bai.scriptedCurrentMeds"), "Amlodipine 5mg", ""],
        [t("bai.scriptedLastVisit"), t("bai.scriptedLastVisitValue"), ""],
      ].forEach(([label, value, className]) => {
        const row = document.createElement("div");
        const labelEl = document.createElement("span");
        const valueEl = document.createElement("b");
        labelEl.textContent = label;
        valueEl.textContent = value;
        if (className) valueEl.className = className;
        row.append(labelEl, valueEl);
        card.appendChild(row);
      });
      target.appendChild(card);
    });
    add(4600, (target) =>
      target.appendChild(
        messageHtml("user", t("bai.scriptedQuestion")),
      ),
    );
    add(5700, (target) => target.appendChild(typingEl()));
    add(7000, (target) => {
      const typing = target.querySelector(".typing");
      if (typing) typing.remove();
      target.appendChild(
        messageHtml(
          "bai",
          t("bai.scriptedResponse"),
        ),
      );
    });
    scriptedChatTimers.push(setTimeout(run, 11000));
  }

  run();
}

